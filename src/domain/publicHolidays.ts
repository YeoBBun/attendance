/** 기본 공휴일 중 아직 없는 날짜만 더한다. 교사가 고치거나 지정한 날짜는 건드리지 않는다. */
export function mergePublicHolidays(existing: Holiday[]): Holiday[] {
  const have = new Set(existing.map((h) => h.date));
  return [...existing, ...PUBLIC_HOLIDAYS.filter((h) => !have.has(h.date))].sort((a, b) => a.date.localeCompare(b.date));
}
